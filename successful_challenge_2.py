from sklearn.metrics import roc_auc_score, roc_curve, average_precision_score, PrecisionRecallDisplay
import numpy as np

# --- AUC & ROC ---
# Extract per-sample pneumonia probability using the same weighted fusion as predict_challenge_class()
pneumonia_probs = [
    0.5  * (p[PNEUMONIA_IDX] if PNEUMONIA_IDX is not None else 0.0) +
    0.35 * (p[CONSOLID_IDX] if CONSOLID_IDX is not None else 0.0)  +
    0.15 * (p[INFILTR_IDX] if INFILTR_IDX is not None else 0.0)
    for p in all_probs
]
y_binary = [1 if y == 'PNEUMONIA' else 0 for y in y_true]

auc = roc_auc_score(y_binary, pneumonia_probs)
print(f'\nROC-AUC: {auc:.4f}')

# Find optimal threshold via Youden's J (maximises sensitivity + specificity simultaneously)
fpr, tpr, thresholds = roc_curve(y_binary, pneumonia_probs)
optimal_idx       = np.argmax(tpr - fpr)
optimal_threshold = thresholds[optimal_idx]
print(f'Optimal threshold (Youden J): {optimal_threshold:.3f}')
print(f'  → Sensitivity at this threshold: {tpr[optimal_idx]*100:.1f}%')
print(f'  → Specificity at this threshold: {(1 - fpr[optimal_idx])*100:.1f}%')
print(f'  → Update THRESHOLD = {optimal_threshold:.3f} in Step 4 cell, then re-run Steps 4→5→6')

# ROC Curve plot
fig, ax = plt.subplots(figsize=(7, 6))
ax.plot(fpr, tpr, color='crimson', lw=2, label=f'ROC (AUC = {auc:.3f})')
ax.plot([0, 1], [0, 1], 'k--', lw=1, label='Random classifier')
ax.scatter(fpr[optimal_idx], tpr[optimal_idx], color='orange', zorder=5, s=80,
           label=f'Optimal threshold = {optimal_threshold:.2f}')
ax.set_xlabel('False Positive Rate (1 − Specificity)')
ax.set_ylabel('True Positive Rate (Sensitivity)')
ax.set_title(f'ROC Curve — {WEIGHTS}', fontsize=12)
ax.legend()
plt.tight_layout()
plt.savefig('roc_curve.png', dpi=120)
