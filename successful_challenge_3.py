import cv2

def estimate_cardiothoracic_ratio(pil_img, debug_plot=False):
    """
    Estimates the cardiothoracic ratio (CTR) from a PIL chest X-ray image.
    This is a heuristic method and should not be used for clinical diagnosis.
    It attempts to find the heart and the thoracic cage boundaries to calculate the ratio.

    Args:
        pil_img (PIL.Image.Image): The input chest X-ray image in PIL format.
        debug_plot (bool): If True, plots intermediate steps for debugging.

    Returns:
        float: The estimated cardiothoracic ratio, or None if estimation fails.
    """
    img_np = np.array(pil_img.convert('L'))

    if debug_plot:
        plt.figure(figsize=(10, 5))
        plt.subplot(1, 4, 1)
        plt.imshow(img_np, cmap='gray')
        plt.title('Original Greyscale')
        plt.axis('off')

    # 1. Preprocessing: Enhance contrast and reduce noise
    blurred = cv2.GaussianBlur(img_np, (5, 5), 0)
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    enhanced_img = clahe.apply(blurred)

    if debug_plot:
        plt.subplot(1, 4, 2)
        plt.imshow(enhanced_img, cmap='gray')
        plt.title('Enhanced')
        plt.axis('off')

    # 2. Thresholding and Morphological Operations to find lung fields and heart
    # Otsu's thresholding to separate foreground (bones, heart) from background (lungs)
    _, thresh = cv2.threshold(enhanced_img, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)
    kernel = np.ones((5, 5), np.uint8)
    opened = cv2.morphologyEx(thresh, cv2.MORPH_OPEN, kernel, iterations=2)
    closed = cv2.morphologyEx(opened, cv2.MORPH_CLOSE, kernel, iterations=3)

    if debug_plot:
        plt.subplot(1, 4, 3)
        plt.imshow(closed, cmap='gray')
        plt.title('Thresholded & Closed')
        plt.axis('off')

    # 3. Find contours: Identify major structures
    contours, _ = cv2.findContours(closed, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    # Filter contours based on size (to remove small noise and keep large structures like lungs/heart)
    min_area = img_np.shape[0] * img_np.shape[1] * 0.01  # e.g., 1% of image area
    large_contours = [c for c in contours if cv2.contourArea(c) > min_area]

    if not large_contours:
        print("No large contours found for CTR estimation.")
        return None

    # Combine all large contours to get a better overall mask
    combined_mask = np.zeros_like(img_np, dtype=np.uint8)
    cv2.drawContours(combined_mask, large_contours, -1, 255, cv2.FILLED)

    # 4. Estimate Thoracic Width
    # Find the leftmost and rightmost points of the combined mask
    coords = np.where(combined_mask == 255)
    if coords[1].size == 0:
        print("Combined mask is empty.")
        return None

    leftmost_thoracic = np.min(coords[1])
    rightmost_thoracic = np.max(coords[1])
    thoracic_width = rightmost_thoracic - leftmost_thoracic

    # 5. Estimate Cardiac Width (Heuristic: find the largest contour near the center)
    # This is highly heuristic and often unreliable without more advanced segmentation
    heart_contour = None
    max_heart_area = 0
    img_center_x = img_np.shape[1] / 2

    for c in large_contours:
        M = cv2.moments(c)
        if M['m00'] > 0:
            cx = int(M['m10'] / M['m00'])
            area = cv2.contourArea(c)
            # Prioritize contours near the center that are not too wide (i.e. not the whole lung field)
            # A crude way to differentiate heart from lungs in a simple contour list
            bbox_x, bbox_y, bbox_w, bbox_h = cv2.boundingRect(c)
            if abs(cx - img_center_x) < img_np.shape[1] * 0.2 and bbox_w < img_np.shape[1] * 0.5: # within central 40% and not too wide
                 if area > max_heart_area:
                    max_heart_area = area
                    heart_contour = c

    if heart_contour is None:
        # Fallback: if no suitable central contour, use the largest one (might be lung)
        # This part makes the cardiac width estimation very brittle.
        print("Warning: Could not robustly identify heart contour. Using largest central object.")
        # Re-evaluate based on centrality and size again, maybe relax bbox_w criterion slightly
        # Or simply take the largest single blob within the central 50% horizontally.
        central_contours = []
        for c in large_contours:
            M = cv2.moments(c)
            if M['m00'] > 0:
                cx = int(M['m10'] / M['m00'])
                if abs(cx - img_center_x) < img_np.shape[1] * 0.25: # central 50%
                    central_contours.append(c)
        if central_contours:
            heart_contour = max(central_contours, key=cv2.contourArea)

    if heart_contour is None:
        print("Could not find a suitable heart contour for CTR estimation.")
        return None

    # Get bounding box for the heart contour
    x, y, w, h = cv2.boundingRect(heart_contour)
    cardiac_width = w

    if debug_plot:
        dbg_img = cv2.cvtColor(img_np, cv2.COLOR_GRAY2BGR)
        cv2.rectangle(dbg_img, (leftmost_thoracic, 0), (rightmost_thoracic, img_np.shape[0]), (0, 255, 0), 2)
        cv2.rectangle(dbg_img, (x, y), (x + w, y + h), (255, 0, 0), 2)
        plt.subplot(1, 4, 4)
        plt.imshow(dbg_img)
        plt.title('Thoracic/Cardiac BBox')
        plt.axis('off')
        plt.tight_layout()
        plt.show()

    if thoracic_width == 0:
        print("Thoracic width is zero, cannot compute CTR.")
        return None

    ctr = cardiac_width / thoracic_width
    return ctr

