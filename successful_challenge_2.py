print('Saved: roc_curve.png')

# --- Precision-Recall Curve ---
pr_auc = average_precision_score(y_binary, pneumonia_probs)
print(f'\nPR-AUC (Average Precision): {pr_auc:.4f}')
fig2, ax2 = plt.subplots(figsize=(7, 6))
PrecisionRecallDisplay.from_predictions(y_binary, pneumonia_probs, ax=ax2)
ax2.set_title(f'Precision-Recall Curve — {WEIGHTS}', fontsize=12)
