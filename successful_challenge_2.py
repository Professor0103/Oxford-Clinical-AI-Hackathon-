"""## Step 9 — Clinical Guardrails

The model outputs 18 continuous probability scores — not hard binary decisions. A safe
clinical deployment must define explicit rules for when to escalate, when to flag
uncertainty, and when to refuse a "normal" verdict.

### Evidence Base
The following thresholds are grounded in:
- Rajpurkar et al. (2017) CheXNet: radiologist-level pneumonia detection requires recall ≥ 0.90
- NHS England AI imaging guidance: human-in-the-loop required for all AI-assisted reporting
- TorchXRayVision validation studies: `all`-weights model achieves AUC ~0.77–0.82 on external data
"""

PNEUMONIA_HARD_FLAG_THRESHOLD = 0.20   # any score above this → mandatory review
UNCERTAINTY_THRESHOLD         = 0.25   # composite confidence below this → uncertain
NORMAL_SAFETY_THRESHOLD       = 0.70   # Normal only returned if confidence ≥ this
NON_CXR_HEURISTIC_THRESHOLD   = 0.03   # Max pathology score below this suggests non-CXR or unrecognisable image

def apply_guardrails(pred_class, confidence, full_findings, is_pediatric=False):
    """Apply clinical safety rules to model output."""
    alerts = []

    # New Rule: Pediatric CXR
    if is_pediatric:
        alerts.insert(0, '🚨 CRITICAL ALERT — Pediatric patient identified. Model not trained on pediatric datasets; cannot provide reliable interpretation. Refer to paediatric radiologist.')
        return 'Pediatric CXR - Caution', alerts # Override predicted class

    # New Rule: Check if image is potentially not a CXR based on overall low pathology scores
    max_overall_prob = max(full_findings.values())
    if max_overall_prob < NON_CXR_HEURISTIC_THRESHOLD:
        alerts.insert(0, f'🚨 CRITICAL ALERT — Unrecognisable image pattern detected (max pathology score {max_overall_prob:.2f}). Referral back to emergency triage recommended.')
        return 'Not CXR / Unrecognisable', alerts # Override predicted class

    # Rule 1: Pneumonia hard flag (any above minimum threshold)
    pneu_raw = max(
        full_findings.get('Pneumonia', 0),
        full_findings.get('Consolidation', 0)
    )
    if pneu_raw >= PNEUMONIA_HARD_FLAG_THRESHOLD:
        alerts.append(f'⚠️  EXPEDITED REVIEW — Pneumonia/Consolidation score {pneu_raw:.2f} '
                      f'(threshold {PNEUMONIA_HARD_FLAG_THRESHOLD})')

    # Rule 2: Uncertainty flag
    if confidence < UNCERTAINTY_THRESHOLD:
        alerts.append(f'⚠️  UNCERTAIN — Max composite score {confidence:.2f} '
                      f'< {UNCERTAINTY_THRESHOLD} — Senior Radiologist Review Required')

    # Rule 3: Normal safety gate
    if pred_class == 'Normal' and confidence < NORMAL_SAFETY_THRESHOLD:
        pred_class = 'Indeterminate'
        alerts.append(f'⚠️  Normal withheld — confidence {confidence:.2f} '
                      f'< {NORMAL_SAFETY_THRESHOLD} safety threshold')

    # Rule 4: Secondary finding alert (borderline scores 0.20–0.40)
    borderline = [(p, v) for p, v in full_findings.items()
                  if 0.20 <= v <= 0.40 and p not in ['Pneumonia','Consolidation','Effusion','Infiltration']]
    if borderline:
        bl_str = ', '.join(f'{p} ({v:.2f})' for p, v in sorted(borderline, key=lambda x: -x[1])[:3])
        alerts.append(f'ℹ️  Borderline secondary findings: {bl_str}')

    return pred_class, alerts

print('OK Clinical guardrails defined.')
print(f'Pneumonia flag threshold:    ≥ {PNEUMONIA_HARD_FLAG_THRESHOLD}')
print(f'Uncertainty threshold:       < {UNCERTAINTY_THRESHOLD}')
print(f'Normal safety gate:          ≥ {NORMAL_SAFETY_THRESHOLD}')
print(f'Non-CXR heuristic threshold: < {NON_CXR_HEURISTIC_THRESHOLD}')

