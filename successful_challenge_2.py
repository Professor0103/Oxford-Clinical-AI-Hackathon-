"""## Step 8 — XAI: Explain the Model with GradCAM

**Why does the model think it sees pneumonia?**

GradCAM (Gradient-weighted Class Activation Mapping) is the standard XAI method for CNN
architectures like DenseNet-121. It computes gradients flowing back from the predicted class
score into the final convolutional layer, then visualises which spatial regions activated most
strongly. This produces a heatmap overlaid on the original X-ray.

### Why GradCAM is Clinically Important
A model that correctly classifies "Pneumonia" but attends to the *left shoulder* instead of
the *right lower lobe* is not clinically trustworthy — it has learned a spurious correlation
(perhaps position of a medical device) rather than true pneumonic consolidation.

GradCAM lets a radiologist verify that the model is looking in the right place.

### XAI Method — for your Slide 2
| Method | Architecture | Output | Status |
|--------|-------------|--------|--------|
| **GradCAM** | DenseNet, ResNet, VGG (CNN) | Class activation heatmap | ✅ This notebook |
| Attention Rollout | Vision Transformer | Patch attention weights | For ViT architectures |
| LIME | Any | Superpixel attribution | Model-agnostic but slow |
| SHAP | Any | Pixel-level attribution | Computationally expensive |
"""

import torch.nn.functional as F
from PIL import Image

def gradcam(model, img_tensor, target_class_name):
    """
    Compute GradCAM heatmap for a target pathology class.
    Works with TorchXRayVision DenseNet-121.
    """
    target_idx = model.pathologies.index(target_class_name)
    gradients  = []
    activations= []

    # Hook: capture gradients at final convolutional layer
    def save_gradient(grad): gradients.append(grad)
    def save_activation(module, input, output):
        activations.append(output)
        output.register_hook(save_gradient)

    # Register hooks on final dense block
    handle = model.features.denseblock4.register_forward_hook(save_activation)

    # Forward pass
    output = torch.sigmoid(model(img_tensor))
    handle.remove()

    # Backward pass from target class
    model.zero_grad()
    output[0, target_idx].backward(retain_graph=True)

    # GradCAM computation
    pooled_grads = gradients[0].mean(dim=[0, 2, 3])       # global average pooling over spatial dims
    act = activations[0][0]                                 # (C, H, W)
    for i in range(act.shape[0]):
        act[i, :, :] *= pooled_grads[i]
    heatmap = act.mean(dim=0).detach().numpy()
    heatmap = np.maximum(heatmap, 0)                        # ReLU
    if heatmap.max() > 0:
        heatmap /= heatmap.max()                            # normalise to [0, 1]
    return heatmap

def display_gradcam(image_path_or_pil, target='Pneumonia'):
    """Classify, compute GradCAM, and display a 3-panel visualisation."""
    if isinstance(image_path_or_pil, str):
        pil_img = Image.open(image_path_or_pil).convert('L')
    else:
        pil_img = image_path_or_pil.convert('L')

    img_tensor = preprocess_image(pil_img)

    # Run GradCAM
    if target not in model.pathologies:
        print(f'Warning: {target} not in model pathologies. Using Pneumonia.')
        target = 'Pneumonia'
    heatmap = gradcam(model, img_tensor, target)

    # Upsample heatmap to original image size
    heatmap_resized = np.array(
        Image.fromarray((heatmap * 255).astype(np.uint8)).resize(pil_img.size, Image.BILINEAR)
    ) / 255.0

    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    orig = np.array(pil_img)

    axes[0].imshow(orig, cmap='gray'); axes[0].set_title('Original X-Ray'); axes[0].axis('off')
    axes[1].imshow(heatmap_resized, cmap='jet'); axes[1].set_title(f'GradCAM: {target}'); axes[1].axis('off')
    axes[2].imshow(orig, cmap='gray')
    axes[2].imshow(heatmap_resized, cmap='jet', alpha=0.45)
